test("the file is replies.jsonl alone and replies-<agent>.jsonl with --agent", async () => {
  const dir = aStateDir();
  await run(dir, ["--item", "itm_a", "--rev", "1", "--status", "handled"]);
  assert.equal(linesIn(dir, "replies.jsonl").length, 1);
  assert.equal(linesIn(dir, "replies-claude.jsonl"), null);

  await run(dir, ["--item", "itm_a", "--rev", "1", "--status", "handled", "--agent", "claude"]);
  assert.equal(linesIn(dir, "replies-claude.jsonl").length, 1);
  assert.equal(linesIn(dir, "replies.jsonl").length, 1, "the shared file was not touched");

  // Both names are ones the helper's discovery will pick up.
  assert.equal(protocol.agentFromFilename("replies.jsonl").ok, true);
  assert.deepEqual(protocol.agentFromFilename("replies-claude.jsonl"), { ok: true, agent: "claude", reason: null });
});

test("an unknown review is refused before anything is written", async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "lahe-reply-empty-"));
  const result = await run(dir, ["--item", "itm_a", "--rev", "1", "--status", "handled"]);
  assert.equal(result.code, protocol.CLI_EXIT.UNKNOWN_REVIEW);
  assert.match(result.stderr, /no review "rev_test"/);
  assert.equal(result.stdout, "");
});

