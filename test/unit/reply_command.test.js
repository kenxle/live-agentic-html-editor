test("--text - reads stdin, keeping interior newlines and dropping one trailing newline", async () => {
  const dir = aStateDir();
  const result = await run(
    dir,
    ["--item", "itm_a", "--rev", "1", "--status", "question", "--text", "-"],
    { stdin: "first paragraph\n\nsecond paragraph\n" }
  );
  assert.equal(result.code, protocol.CLI_EXIT.OK, result.stderr);
  assert.deepEqual(JSON.parse(linesIn(dir, "replies.jsonl")[0]), {
    item: "itm_a",
    rev: 1,
    status: "question",
    text: "first paragraph\n\nsecond paragraph"
  });
});

test("a pipe with neither --text nor --reason is read as the text", async () => {
  const dir = aStateDir();
  const result = await run(
    dir,
    ["--item", "itm_a", "--rev", "1", "--status", "handled"],
    { stdin: "carried this into the template\n", stdinIsTty: false }
  );
  assert.equal(result.code, protocol.CLI_EXIT.OK, result.stderr);
  assert.equal(JSON.parse(linesIn(dir, "replies.jsonl")[0]).text, "carried this into the template");
});

test("a --reason given on the command line is not overwritten by an inherited pipe", async () => {
  const dir = aStateDir();
  await run(
    dir,
    ["--item", "itm_a", "--rev", "1", "--status", "not_handled", "--reason", "no such file"],
    { stdin: "something else entirely\n", stdinIsTty: false }
  );
  const written = JSON.parse(linesIn(dir, "replies.jsonl")[0]);
  assert.equal(written.reason, "no such file");
  assert.equal(Object.prototype.hasOwnProperty.call(written, "text"), false);
});

test("--text - with an empty stdin is a refusal, not a reply with nothing in it", async () => {
  const dir = aStateDir();
  const result = await run(dir, ["--item", "itm_a", "--rev", "1", "--status", "question", "--text", "-"], { stdin: "" });
  assert.equal(result.code, protocol.CLI_EXIT.BAD_USAGE);
  assert.match(result.stderr, /--text - read nothing from stdin/);
  assert.equal(linesIn(dir, "replies.jsonl"), null);
});

// ---------------------------------------------------------------------------
// The rev warning, which is a warning and never a refusal
// ---------------------------------------------------------------------------

test("a rev the projection disagrees with warns on stderr and still writes the line", async () => {
  const dir = aStateDir();
  const log = require("../../src/service/log.js").createEventLog({ dir: dir });
  const record = require("../../src/shared/record.js");
  const item = record.newItem({
    id: "itm_live",
    kind: record.KIND.COMMENT,
    state: record.STATE.READY,
    rev: 3,
    page_origin: record.FILE_ORIGIN,
    page_path: "brief.html",
    note: "tighten this"
  });
  log.append(REVIEW, [
    protocol.newEvent({
      event: protocol.EVENT.REVIEW_CREATED,
      event_id: "ev_created",
      review: REVIEW,
      payload: { token: "t".repeat(8) }
    }),
    protocol.newEvent({
      event: protocol.EVENT.ITEM_READY,
      event_id: "ev_item",
      review: REVIEW,
      item: item[record.FIELD.ID],
      rev: item[record.FIELD.REV],
      page_path: item[record.FIELD.PAGE_PATH],
      page_seq: item[record.FIELD.PAGE_SEQ],
      payload: { draft: false, record: item }
    })
  ]);

  const stale = await run(dir, ["--item", "itm_live", "--rev", "2", "--status", "handled"]);
  assert.equal(stale.code, protocol.CLI_EXIT.OK, "a second opinion about the rev never costs the agent its reply");
  assert.match(stale.stderr, /item itm_live is at rev 3 and you passed 2/);
  assert.equal(linesIn(dir, "replies.jsonl").length, 1);

  const current = await run(dir, ["--item", "itm_live", "--rev", "3", "--status", "handled"]);
  assert.equal(current.stderr, "", "the matching rev says nothing");

  const unknown = await run(dir, ["--item", "itm_nowhere", "--rev", "1", "--status", "handled"]);
  assert.equal(unknown.code, protocol.CLI_EXIT.OK);
  assert.match(unknown.stderr, /no item "itm_nowhere" in review rev_test/);
});

