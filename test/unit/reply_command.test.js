// `lahe reply`: the one command that writes a reply line, so no shell has to
// encode JSON.
//
// The incident this exists for: an agent appended a reply with a shell echo and
// a multi-paragraph answer. The raw newlines inside the JSON string split one
// object across three physical lines, the helper rejected all three, and the
// reviewer got a malformed-line warning on the rail. The load-bearing assertion
// in this file is therefore the EXACT BYTES for text with newlines and quotes,
// plus the round trip back through protocol.parseReplyLine, which is the same
// parser the helper's fold uses.

"use strict";

const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const reply = require("../../src/cli/commands/reply.js");
const protocol = require("../../src/shared/protocol.js");

const REVIEW = "rev_test";

function aStateDir() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "lahe-reply-"));
  fs.mkdirSync(path.join(dir, "reviews", REVIEW), { recursive: true });
  return dir;
}

async function run(dir, args, options) {
  const stdout = [];
  const stderr = [];
  const code = await reply.run(
    ["--review", REVIEW, "--state-dir", dir].concat(args),
    Object.assign(
      {
        stdout: (text) => stdout.push(String(text)),
        stderr: (text) => stderr.push(String(text)),
        // No test reads the real stdin: an inherited pipe would make these
        // assertions depend on how the suite was launched.
        stdinIsTty: true
      },
      options || {}
    )
  );
  return { code: code, stdout: stdout.join(""), stderr: stderr.join("") };
}

function linesIn(dir, filename) {
  const file = path.join(dir, "reviews", REVIEW, filename);
  if (!fs.existsSync(file)) return null;
  return fs.readFileSync(file, "utf8").split("\n").filter((line) => line !== "");
}

// ---------------------------------------------------------------------------
// The bytes, which are the whole point
// ---------------------------------------------------------------------------

test("a text with paragraph breaks and quotes is ONE physical line the fold can read", async () => {
  const dir = aStateDir();
  const answer = 'Two things.\n\nFirst, the "wrapper" is gone.\nSecond, it is a tab \there.';
  const result = await run(dir, ["--item", "itm_ab12", "--rev", "2", "--status", "question", "--text", answer]);

  assert.equal(result.code, protocol.CLI_EXIT.OK, result.stderr);

  const raw = fs.readFileSync(path.join(dir, "reviews", REVIEW, "replies.jsonl"), "utf8");
  assert.equal(raw.split("\n").length, 2, "one line plus the trailing newline, never three");
  assert.equal(
    raw,
    '{"item":"itm_ab12","rev":2,"status":"question","text":"Two things.\\n\\nFirst, the \\"wrapper\\" is gone.\\nSecond, it is a tab \\there."}\n'
  );
  // The line it printed is the line it wrote, so an agent can see what landed.
  assert.equal(result.stdout, raw);

  const parsed = protocol.parseReplyLine(raw.trim(), { filenameAgent: null });
  assert.equal(parsed.ok, true, parsed.reason);
  assert.equal(parsed.reply[protocol.REPLY_FIELD.TEXT], answer, "the newlines survive the round trip");
});

test("every optional field lands under the protocol's own names, and appends rather than replaces", async () => {
  const dir = aStateDir();
  const first = await run(dir, [
    "--item", "itm_one", "--rev", "1", "--status", "not_handled",
    "--reason", "the source file is generated by a build I cannot run",
    "--agent", "claude", "--file", "src/a.html", "--file", "src/b.html", "--needs-see"
  ]);
  assert.equal(first.code, protocol.CLI_EXIT.OK, first.stderr);

  const second = await run(dir, ["--item", "itm_two", "--rev", "3", "--status", "handled", "--agent", "claude"]);
  assert.equal(second.code, protocol.CLI_EXIT.OK, second.stderr);

  const lines = linesIn(dir, "replies-claude.jsonl");
  assert.equal(lines.length, 2, "the second reply appended; nothing was rewritten");
  assert.deepEqual(JSON.parse(lines[0]), {
    item: "itm_one",
    rev: 1,
    status: "not_handled",
    agent: "claude",
    reason: "the source file is generated by a build I cannot run",
    files: ["src/a.html", "src/b.html"],
    user_needs_to_see_reply: true
  });
  // A handled reply carries nothing it was not given: no empty reason, no
  // false flag, nothing for the reviewer's card to render as blank.
  assert.deepEqual(JSON.parse(lines[1]), { item: "itm_two", rev: 3, status: "handled", agent: "claude" });
});

