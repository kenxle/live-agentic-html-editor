test("the validation refusals name what is wrong and write no line at all", async () => {
  const cases = [
    { args: ["--item", "itm_a", "--rev", "1"], expect: /--status is required/ },
    { args: ["--item", "itm_a", "--rev", "1", "--status", "done"], expect: /--status must be one of handled, not_handled, question/ },
    { args: ["--rev", "1", "--status", "handled"], expect: /--item is required/ },
    { args: ["--item", "itm_a", "--status", "handled"], expect: /--rev is required/ },
    { args: ["--item", "itm_a", "--rev", "2.5", "--status", "handled"], expect: /--rev must be an integer/ },
    { args: ["--item", "itm_a", "--rev", "later", "--status", "handled"], expect: /--rev must be an integer/ },
    { args: ["--item", "itm_a", "--rev", "1", "--status", "question"], expect: /--status question needs --text/ },
    { args: ["--item", "itm_a", "--rev", "1", "--status", "not_handled"], expect: /--status not_handled needs --reason/ },
    { args: ["--item", "itm_a", "--rev", "1", "--status", "handled", "--needs-see"], expect: /--needs-see needs --text or --reason/ },
    { args: ["--item", "itm_a", "--rev", "1", "--status", "handled", "--agent", "../evil"], expect: /--agent names a file too/ },
    { args: ["--item", "../evil", "--rev", "1", "--status", "handled"], expect: /--item must be an item id/ },
    { args: ["--item", "itm_a", "--rev", "1", "--status", "handled", "--file"], expect: /--file needs a value/ },
    { args: ["--item", "itm_a", "--rev", "1", "--status", "handled", "--nope"], expect: /unknown option "--nope"/ }
  ];

  for (const one of cases) {
    const dir = aStateDir();
    const result = await run(dir, one.args);
    assert.equal(result.code, protocol.CLI_EXIT.BAD_USAGE, one.args.join(" "));
    assert.match(result.stderr, one.expect);
    assert.equal(result.stdout, "", one.args.join(" ") + " printed nothing on stdout");
    assert.equal(linesIn(dir, "replies.jsonl"), null, one.args.join(" ") + " wrote no file");
  }
});

test("the needs-see refusal quotes the contract rule rather than paraphrasing it", async () => {
  const reviewFormat = require("../../src/shared/review_format.js");
  const dir = aStateDir();
  const result = await run(dir, ["--item", "itm_a", "--rev", "1", "--status", "handled", "--needs-see"]);
  const quoted = "the flag counts only when the same line carries text or reason; flagging a reply with nothing in it sends the reviewer to a card that says nothing";
  assert.ok(result.stderr.includes(quoted), "the refusal carries the contract's own words");
  assert.ok(
    reviewFormat.CONTRACT.some((sentence) => sentence.includes(quoted)),
    "and those words are still in the contract"
  );
});

